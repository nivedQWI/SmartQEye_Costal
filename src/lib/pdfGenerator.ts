import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { formatISTFull } from '@/lib/utils';
import { auditApi } from '@/lib/api';

export interface ReportPdfOptions {
  reportId: string;
  reportType: string;
  title: string;
  generatedBy: string;
  officerRole: string;
  periodCovered: string;
  classification?: string;
  stationJurisdiction?: string;
  executiveSummary?: string;
  tableHead: string[][];
  tableBody: (string | number)[][];
  additionalNotes?: string[];
  signOffOfficer?: string;
}

/**
 * Calculates SHA-256 hex string using Web Crypto API
 */
async function computeSha256(data: string | Uint8Array): Promise<string> {
  const bytes = typeof data === 'string' ? new TextEncoder().encode(data) : data;
  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  const hashBuffer = await crypto.subtle.digest('SHA-256', copy.buffer as ArrayBuffer);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

/**
 * Generates an official Kerala Police Coastal Intelligence Report PDF
 */
export async function generatePoliceReportPdf(options: ReportPdfOptions): Promise<{
  blob: Blob;
  filename: string;
  sha256: string;
}> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  const contentWidth = pageWidth - margin * 2;

  // ── Header Letterhead ──
  // Header background bar
  doc.setFillColor(18, 48, 63); // Deep ocean ink #12303F
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Emblem / Organization Text
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('KERALA POLICE · STATE COASTAL SECURITY DIVISION', pageWidth / 2, 9, { align: 'center' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(200, 225, 240);
  doc.text('CYBER DIVISION — DRONE FORENSIC LAB · STATE CRIME RECORDS BUREAU', pageWidth / 2, 14, { align: 'center' });
  doc.text('SmartQEye Coastal AI Platform · Quantumweave Intelligence Pvt. Ltd.', pageWidth / 2, 19, { align: 'center' });

  // Classification Sub-bar
  doc.setFillColor(235, 75, 30); // Alert vermilion
  doc.rect(0, 23, pageWidth, 5, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(255, 255, 255);
  doc.text(
    (options.classification || 'CONFIDENTIAL — FOR AUTHORISED POLICE INTERNAL USE ONLY').toUpperCase(),
    pageWidth / 2,
    26.5,
    { align: 'center' }
  );

  // ── Report Title & Document Info Box ──
  let yPos = 36;
  doc.setTextColor(18, 48, 63);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(options.title, margin, yPos);

  yPos += 5;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(80, 95, 105);
  doc.text(`Official Police Intelligence Record · RFP §5.1.27 & §11 Compliance`, margin, yPos);

  // Metadata Grid Table (using autotable)
  yPos += 4;
  const metadataRows = [
    ['Document ID:', options.reportId, 'Jurisdiction / Base:', options.stationJurisdiction || 'Vizhinjam Coastal Police Station'],
    ['Report Type:', options.reportType.replace(/_/g, ' '), 'Period Covered:', options.periodCovered],
    ['Generated By:', `${options.generatedBy} (${options.officerRole})`, 'Timestamp (IST):', formatISTFull(new Date().toISOString())],
    ['Sign-Off Officer:', options.signOffOfficer || 'Superintendent of Police, Coastal Operations', 'Legal Regime:', 'Section 65B Indian Evidence Act / Sec 63 BNSS'],
  ];

  autoTable(doc, {
    startY: yPos,
    margin: { left: margin, right: margin },
    body: metadataRows,
    theme: 'plain',
    styles: {
      fontSize: 8,
      cellPadding: 1.5,
      textColor: [30, 41, 59],
    },
    columnStyles: {
      0: { fontStyle: 'bold', textColor: [71, 85, 105], cellWidth: 30 },
      1: { cellWidth: 60 },
      2: { fontStyle: 'bold', textColor: [71, 85, 105], cellWidth: 32 },
      3: { cellWidth: 60 },
    },
  });

  yPos = (doc as any).lastAutoTable.finalY + 4;

  // ── Executive Summary ──
  if (options.executiveSummary) {
    doc.setFillColor(245, 248, 250);
    doc.setDrawColor(200, 215, 225);
    doc.roundedRect(margin, yPos, contentWidth, 18, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(18, 48, 63);
    doc.text('EXECUTIVE OPERATIONAL SUMMARY:', margin + 3, yPos + 4.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(51, 65, 85);
    const splitSummary = doc.splitTextToSize(options.executiveSummary, contentWidth - 6);
    doc.text(splitSummary, margin + 3, yPos + 9);

    yPos += 22;
  }

  // ── Main Data Table ──
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(18, 48, 63);
  doc.text('RECORDED OPERATIONAL DATA & OBSERVATIONS', margin, yPos);
  yPos += 2;

  autoTable(doc, {
    startY: yPos,
    margin: { left: margin, right: margin },
    head: options.tableHead,
    body: options.tableBody,
    theme: 'striped',
    headStyles: {
      fillColor: [43, 127, 166], // Sea blue #2B7FA6
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: 'bold',
      halign: 'left',
    },
    styles: {
      fontSize: 7.5,
      cellPadding: 2,
      textColor: [30, 41, 59],
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
  });

  yPos = (doc as any).lastAutoTable.finalY + 6;

  // ── Check page overflow for attestation footer ──
  if (yPos > pageHeight - 45) {
    doc.addPage();
    yPos = 20;
  }

  // ── Section 65B Attestation Block ──
  doc.setFillColor(254, 252, 245);
  doc.setDrawColor(220, 205, 160);
  doc.roundedRect(margin, yPos, contentWidth, 24, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(140, 90, 20);
  doc.text('STATUTORY ELECTRONIC EVIDENCE ATTESTATION (SEC 65B IEA / SEC 63 BNSS):', margin + 3, yPos + 4.5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(70, 75, 80);
  const legalText =
    'Certified that this document contains computer-generated data captured by SmartQEye Coastal during the period specified. ' +
    'The system operated within standard operational parameters without malfunction, and cryptographic integrity hashes guarantee unaltered provenance.';
  doc.text(doc.splitTextToSize(legalText, contentWidth - 6), margin + 3, yPos + 9);

  // Digital Signature Block
  yPos += 28;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(50, 60, 70);
  doc.text('Attested & Verified By:', margin, yPos);
  doc.text('State Command Seal & Endorsement:', pageWidth - margin - 60, yPos);

  yPos += 4;
  doc.setFont('helvetica', 'bold');
  doc.text(`${options.generatedBy} (${options.officerRole})`, margin, yPos);
  doc.text('Kerala Police Drone Forensic Lab HQ', pageWidth - margin - 60, yPos);

  // ── Running Footers with Dynamic Page Numbers ──
  const totalPages = (doc.internal as any).getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);

    doc.setDrawColor(215, 225, 230);
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(130, 140, 150);
    doc.text(
      'SmartQEye Coastal — Quantumweave Intelligence Pvt. Ltd. · Kerala Police Confidential Record',
      margin,
      pageHeight - 8
    );
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - margin, pageHeight - 8, { align: 'right' });
  }

  // ── Calculate Document Seal Hash ──
  const pdfBytes = doc.output('arraybuffer');
  const sha256 = await computeSha256(new Uint8Array(pdfBytes));

  const filename = `${options.reportId}_${options.reportType.toLowerCase()}_${Date.now()}.pdf`;
  const blob = new Blob([pdfBytes], { type: 'application/pdf' });

  // ── Audit Ledger Append ──
  auditApi.append({
    userId: 'rep-gen',
    userName: options.generatedBy,
    userRole: 'ANALYST',
    action: 'EXPORT_EVIDENCE',
    targetType: 'REPORT',
    targetId: options.reportId,
    beforeAfterSummary: `Generated and cryptographically sealed official PDF report "${options.title}" (SHA-256: ${sha256.slice(0, 16)}…)`,
    outcome: 'SUCCESS',
  }).catch(console.error);

  return { blob, filename, sha256 };
}

/**
 * Downloads a Blob directly in browser
 */
export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
